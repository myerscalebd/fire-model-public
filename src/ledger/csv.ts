/**
 * Minimal RFC-4180 CSV parser: quoted fields, escaped quotes ("") and CRLF/LF
 * line endings. Bank exports are small, so a simple state machine is plenty.
 * Blank lines are dropped.
 */
export function parseCsv(text: string): string[][] {
  const s = text.replace(/^﻿/, ""); // strip a UTF-8 BOM some banks emit
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let inQuotes = false;

  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (inQuotes) {
      if (c === '"') {
        if (s[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += c;
      }
      continue;
    }
    if (c === '"') inQuotes = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (c !== "\r") {
      field += c;
    }
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((f) => f.trim() !== ""));
}
